/**
 * Builds the Typed Accessor runtime that `varlatch types` embeds in every
 * generated module: one esbuild bundle of src/runtime.ts and the Contract
 * Semantics it imports, wrapped in a single function declaration, written to
 * dist/embedded.js as a string. The output depends only on the sources and
 * the pinned esbuild version, so one generator version always embeds the
 * same bytes.
 */
import { build } from "esbuild";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
export const RUNTIME_NAME = "varlatchAccessorRuntime";

/** The runtime source, built in memory. */
export async function buildRuntimeSource() {
  const result = await build({
    absWorkingDir: root,
    entryPoints: ["src/runtime.ts"],
    bundle: true,
    write: false,
    format: "cjs",
    // No Node built-ins and no externals: the generated module must run as is.
    platform: "neutral",
    target: "es2020",
    charset: "ascii",
    legalComments: "none",
    logLevel: "warning",
  });
  // The generated module is an ES module, strict already; a directive inside
  // the wrapper would only be a stray expression.
  const code = result.outputFiles[0].text.replace(/^"use strict";\n/, "").trimEnd();
  if (/\brequire\(/.test(code)) {
    throw new Error("the accessor bundle must not require anything: it is embedded in generated modules as is");
  }
  // A function declaration is hoisted, so the generated module can call it
  // before the point where it is written, at the end of the file.
  return `function ${RUNTIME_NAME}() {\nvar module = { exports: {} };\n${code}\nreturn module.exports;\n}`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const source = await buildRuntimeSource();
  const header = "// Generated by packages/accessor/scripts/bundle.mjs. Do not edit.\n";
  mkdirSync(join(root, "dist"), { recursive: true });
  writeFileSync(
    join(root, "dist", "embedded.js"),
    `${header}export const ACCESSOR_RUNTIME_NAME = ${JSON.stringify(RUNTIME_NAME)};\nexport const ACCESSOR_RUNTIME_SOURCE = ${JSON.stringify(source)};\n`,
  );
  writeFileSync(
    join(root, "dist", "embedded.d.ts"),
    `${header}/** The name of the function ACCESSOR_RUNTIME_SOURCE declares. */\nexport declare const ACCESSOR_RUNTIME_NAME: string;\n/** The bundled Typed Accessor runtime: one function declaration that returns the runtime's exports. */\nexport declare const ACCESSOR_RUNTIME_SOURCE: string;\n`,
  );
}
