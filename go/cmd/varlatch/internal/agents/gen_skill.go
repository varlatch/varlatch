// gen_skill writes skillfiles.gen.go from apps/cli/skill/varlatch, the
// skill's source, as apps/cli/scripts/embed-skill.mjs writes the
// TypeScript CLI's skillFiles.generated.ts: every file, walked with each
// directory's entries in localeCompare's order (for these ASCII names,
// case-insensitive first).
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

const source = "../../../../../apps/cli/skill/varlatch"

func main() {
	var b bytes.Buffer
	b.WriteString("// SPDX-License-Identifier: Apache-2.0\n\n")
	b.WriteString("// Code generated by gen_skill.go from apps/cli/skill/varlatch. DO NOT EDIT.\n\n")
	b.WriteString("package agents\n\n")
	b.WriteString("// skillFiles is the skill's source, by path inside the skill directory.\n")
	b.WriteString("var skillFiles = []skillFile{\n")
	var walk func(dir string)
	walk = func(dir string) {
		entries, err := os.ReadDir(dir)
		if err != nil {
			log.Fatal(err)
		}
		sort.SliceStable(entries, func(i, j int) bool {
			a, c := strings.ToLower(entries[i].Name()), strings.ToLower(entries[j].Name())
			if a != c {
				return a < c
			}
			return entries[i].Name() < entries[j].Name()
		})
		for _, e := range entries {
			path := filepath.Join(dir, e.Name())
			if e.IsDir() {
				walk(path)
				continue
			}
			data, err := os.ReadFile(path)
			if err != nil {
				log.Fatal(err)
			}
			rel, _ := filepath.Rel(source, path)
			fmt.Fprintf(&b, "\t{%s, %s},\n", strconv.Quote(filepath.ToSlash(rel)), strconv.Quote(string(data)))
		}
	}
	walk(source)
	b.WriteString("}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("skillfiles.gen.go", out, 0o644); err != nil {
		log.Fatal(err)
	}
}
