package agents

//go:generate go run gen_skill.go

import (
	"strings"
)

// The agent skill (ADR-0043 Decision 7), a port of
// apps/cli/src/agents/skill.ts: one agent-neutral skill in the open Agent
// Skills format, embedded in the CLI so the installed copy always matches
// the CLI that runs its commands. Source: apps/cli/skill/varlatch, copied
// into skillfiles.gen.go by gen_skill.go (`go generate`); TestSkillFilesCurrent
// fails when the copy is stale.

// SkillName is the skill's directory name.
const SkillName = "varlatch"

// guideTopic is one `varlatch agents guide <topic>`: a reference file.
type guideTopic struct{ topic, path string }

// guideTopics are skill.ts's GUIDE_TOPICS, in order.
var guideTopics = []guideTopic{
	{"setup", "references/setup.md"},
	{"run", "references/run.md"},
	{"agent-run", "references/agent-run.md"},
	{"self-hosting", "references/self-hosting.md"},
	{"contract", "references/contract.md"},
}

func skillSource(path string) string {
	for _, f := range skillFiles {
		if f.path == path {
			return f.content
		}
	}
	return ""
}

// generatedNote is a reference file's first line: it is generated, and
// installing again overwrites edits.
func generatedNote(version string) string {
	return "<!-- Generated by varlatch " + version + ": `varlatch agents install` overwrites edits to this file. -->\n"
}

// skillFile is one file of the skill, by its path inside the skill directory.
type skillFile struct{ path, content string }

// SkillFiles is skillFiles(version): the skill's files for this CLI
// version, in the generated module's order.
func SkillFiles(version string) []skillFile {
	out := make([]skillFile, len(skillFiles))
	for i, f := range skillFiles {
		if f.path == "SKILL.md" {
			out[i] = skillFile{f.path, strings.ReplaceAll(f.content, "{{VERSION}}", version)}
		} else {
			out[i] = skillFile{f.path, generatedNote(version) + f.content}
		}
	}
	return out
}

// skillBody is SKILL.md without its frontmatter.
func skillBody() string {
	content := skillSource("SKILL.md")
	end := strings.Index(content[4:], "\n---\n") + 4
	return strings.TrimLeft(content[end+5:], "\n")
}

// GuideTopicError is skill.ts's GuideTopicError.
type GuideTopicError struct{ Message string }

func (e *GuideTopicError) Error() string { return e.Message }

// Guide is `varlatch agents guide [topic]`: the skill, or one reference,
// for a coding agent with a shell but no skill support. topic "" is none.
func Guide(topic string, given bool) (string, error) {
	names := make([]string, len(guideTopics))
	for i, t := range guideTopics {
		names[i] = t.topic
	}
	if !given {
		return trimEnd(skillBody()) + "\n\nTopics: " + strings.Join(names, ", ") + " (varlatch --assisted agents guide <topic>)\n", nil
	}
	for _, t := range guideTopics {
		if t.topic == topic {
			return skillSource(t.path), nil
		}
	}
	return "", &GuideTopicError{"no guide topic " + topic + "; topics: " + strings.Join(names, ", ")}
}
