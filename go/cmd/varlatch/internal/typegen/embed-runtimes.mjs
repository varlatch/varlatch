/**
 * Copies the Typed Accessor runtimes the TypeScript CLI embeds into
 * embedded/, for the Go CLI's `varlatch types` (internal
 * docs/design/go-cli.md, decision 7): run by `go generate` in this
 * directory, and go.yml fails when the copies are stale.
 *
 * Built by the packages' own scripts, as their builds build them:
 *   - accessor-runtime.js.txt: ACCESSOR_RUNTIME_SOURCE
 *     (packages/accessor/scripts/bundle.mjs, esbuild pinned in its package);
 *   - python-runtime.py.txt: PYTHON_RUNTIME_SOURCE
 *     (packages/accessor-python/scripts/embed.mjs);
 *   - runtimes.json: the runtime's function name, its SCHEMA_FORMAT and the
 *     semantics versions each runtime implements, read from the runtime
 *     itself (the TypeScript one evaluated as generated modules call it).
 * The copies are .txt so no tool takes them for sources, and are never
 * converted at checkout (.gitattributes).
 */
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..", "..", "..", "..");
const run = (...args) => execFileSync("pnpm", args, { cwd: root, stdio: ["ignore", "ignore", "inherit"] });

// The packages' dependencies (esbuild; @varlatch/contract, which the
// TypeScript runtime bundles from its build).
run("install", "--frozen-lockfile", "--filter", "@varlatch/accessor...", "--filter", "@varlatch/accessor-python...");
run("--filter", "@varlatch/contract", "build");

const accessor = await import(pathToFileURL(join(root, "packages/accessor/scripts/bundle.mjs")).href);
const python = await import(pathToFileURL(join(root, "packages/accessor-python/scripts/embed.mjs")).href);

const typescriptSource = await accessor.buildRuntimeSource();
const runtime = new Function(`${typescriptSource}\nreturn ${accessor.RUNTIME_NAME}();`)();
const pythonSource = python.buildRuntimeSource();

const out = join(here, "embedded");
writeFileSync(join(out, "accessor-runtime.js.txt"), typescriptSource);
writeFileSync(join(out, "python-runtime.py.txt"), pythonSource);
writeFileSync(
  join(out, "runtimes.json"),
  `${JSON.stringify(
    {
      comment: "Generated by embed-runtimes.mjs (go generate) from packages/accessor and packages/accessor-python. Do not edit.",
      accessorRuntimeName: accessor.RUNTIME_NAME,
      schemaFormat: runtime.SCHEMA_FORMAT,
      typescriptSemanticsVersions: runtime.implementedSemanticsVersions(),
      pythonSemanticsVersions: python.implementedVersions(),
    },
    null,
    2,
  )}\n`,
);
