package whatwg

import (
	"sort"
	"strings"
	"unicode/utf8"

	"golang.org/x/net/idna"
	"golang.org/x/text/unicode/norm"
)

// Domain to ASCII as Node.js's URL host parser carries it out (ada's
// to_ascii and is_label_valid; the URL Standard's beStrict false, with
// CheckBidi and CheckJoiners), so that Go accepts and refuses the hosts the
// TypeScript server does:
//
//   - an all-ASCII domain is lowercased, nothing more;
//   - otherwise every code point is mapped (UTS #46, nontransitional), the
//     result must hold only code points ada keeps as themselves, and is put
//     in NFC;
//   - per label: an ASCII label is kept; an xn-- label must decode to a
//     non-ASCII label that maps and normalizes to itself and is valid; any
//     other label must be valid and is encoded.
//
// A label is valid (is_label_valid) when it does not begin with a
// combining mark; its first ZWNJ or ZWJ, if any, settles it (ContextJ: after
// a virama, or a ZWNJ between a left- or dual-joining and a right- or
// dual-joining character); otherwise, only when it holds an R, AL or AN
// character, it must meet RFC 5893's conditions. The joiner rule returns
// before the Bidi check, as ada's does.
//
// The mapping is x/net's; which code points ada keeps, and their
// combining, Bidi and joining properties, come from Node itself
// (nodeidna_table.go, generated by testdata/nodeidna.mjs), since ada's
// tables follow neither the current Unicode data nor x/net's. The tests
// hold every code point, in fifteen labels, to Node's answers.

// idnaRange is a range of code points with the same properties.
type idnaRange struct {
	lo, hi rune
	p      uint8
}

// Properties (nodeidna_table.go). Bits 2 to 4 are the Bidi group.
const (
	pValid  = 1 << 0 // ada keeps the code point as itself
	pComb   = 1 << 1 // a combining mark: no label begins with one
	pJoinLD = 1 << 5 // joining type L or D (before a ZWNJ)
	pJoinRD = 1 << 6 // joining type R or D (after a ZWNJ)
	pVirama = 1 << 7 // a virama (before a ZWNJ or ZWJ)
)

// Bidi groups: the classes ada's rules tell apart. gLX is L and every class
// no rule allows, which behave the same.
const (
	gLX = iota
	gRAL
	gAN
	gEN
	gNSM
	gNEU // ES, CS, ET, ON, BN
)

func props(r rune) uint8 {
	i := sort.Search(len(nodeIDNA), func(i int) bool { return nodeIDNA[i].hi >= r })
	if i < len(nodeIDNA) && nodeIDNA[i].lo <= r {
		return nodeIDNA[i].p
	}
	return 0
}

func group(r rune) int { return int(props(r)>>2) & 7 }

// mapper is UTS #46 mapping alone: no validation, which the properties do.
var mapper = idna.New(
	idna.MapForLookup(),
	idna.Transitional(false),
	idna.ValidateLabels(false),
	idna.StrictDomainName(false),
	idna.CheckHyphens(false),
	idna.CheckJoiners(false),
	idna.VerifyDNSLength(false),
)

func mapRune(r rune) string {
	if r < utf8.RuneSelf {
		if 'A' <= r && r <= 'Z' {
			r += 'a' - 'A'
		}
		return string(r)
	}
	s, _ := mapper.ToUnicode(string(r))
	return s
}

// mapAll maps s and reports whether every code point of the result is one
// ada keeps (its map fails otherwise).
func mapAll(s string) (string, bool) {
	var b strings.Builder
	for _, r := range s {
		b.WriteString(mapRune(r))
	}
	out := b.String()
	for _, r := range out {
		if r != '.' && props(r)&pValid == 0 {
			return "", false
		}
	}
	return out, true
}

// maxDomainBytes is ada's limit on the input of to_ascii, which an
// all-ASCII domain never reaches: Node.js lowercases one of any length.
const maxDomainBytes = 16384

// domainToASCII is the URL Standard's domain to ASCII as Node.js carries it
// out: the ASCII lowercase of an all-ASCII domain, or ada's to_ascii.
func domainToASCII(domain string) (string, bool) {
	if isASCII(domain) {
		return strings.ToLower(domain), domain != ""
	}
	if len(domain) > maxDomainBytes || !utf8.ValidString(domain) {
		return "", false
	}
	mapped, ok := mapAll(domain)
	if !ok {
		return "", false
	}
	mapped = norm.NFC.String(mapped)
	labels := strings.Split(mapped, ".")
	for i, label := range labels {
		switch {
		case label == "":
		case strings.HasPrefix(label, "xn--"):
			if !isASCII(label) || !validACE(label) {
				return "", false
			}
		case isASCII(label):
		default:
			if !labelValid([]rune(label)) {
				return "", false
			}
			ace, err := idna.Punycode.ToASCII(label)
			if err != nil {
				return "", false
			}
			labels[i] = ace
		}
	}
	out := strings.Join(labels, ".")
	return out, out != ""
}

// validACE: an xn-- label decodes to a non-ASCII label that maps and
// normalizes to itself and is valid.
func validACE(label string) bool {
	u, err := idna.Punycode.ToUnicode(label)
	if err != nil || u == "" || isASCII(u) || strings.Contains(u, ".") {
		return false
	}
	if m, ok := mapAll(u); !ok || m != u {
		return false
	}
	return norm.NFC.IsNormalString(u) && labelValid([]rune(u))
}

func anyWith(rs []rune, bit uint8) bool {
	for _, r := range rs {
		if props(r)&bit != 0 {
			return true
		}
	}
	return false
}

// labelValid is ada's is_label_valid.
func labelValid(label []rune) bool {
	if len(label) == 0 {
		return true
	}
	if props(label[0])&pComb != 0 {
		return false
	}
	for i, c := range label {
		if c != 0x200c && c != 0x200d {
			continue
		}
		if i > 0 && props(label[i-1])&pVirama != 0 {
			return true
		}
		if c == 0x200d || i == 0 || i+1 >= len(label) {
			return false
		}
		return anyWith(label[:i], pJoinLD) && anyWith(label[i+1:], pJoinRD)
	}
	last := len(label) - 1
	for last >= 0 && group(label[last]) == gNSM {
		last--
	}
	if last < 0 {
		return false
	}
	rtl := false
	for _, c := range label {
		if g := group(c); g == gRAL || g == gAN {
			rtl = true
		}
	}
	if !rtl {
		return true
	}
	if group(label[0]) == gLX {
		// An LTR label holding an R, AL or AN character: never valid. (ada
		// tests the LTR conditions here, which such a character fails.)
		return false
	}
	if group(label[0]) != gRAL {
		return false
	}
	hasAN, hasEN := false, false
	for i := 0; i <= last; i++ {
		switch group(label[i]) {
		case gAN:
			hasAN = true
		case gEN:
			hasEN = true
		case gLX:
			return false
		}
		if hasAN && hasEN {
			return false
		}
	}
	switch group(label[last]) {
	case gRAL, gAN, gEN:
		return true
	}
	return false
}
