// Invitations (ADR-0006, ADR-0010; domain/bootstrap.ts issueInviteGrant,
// domain/invitations.ts): links an admin hands out, never emails. An
// invitation is an `invite` setup grant: the token is shown once, at
// issuance, and only its hash is stored.

// InviteTTL is INVITE_TTL_MS: an invitation lasts seven days.
const InviteTTL = 7 * 24 * time.Hour

// Invitation is a setup grant of kind invite, as listed.
type Invitation struct {
	ID         string
	Name       sql.NullString
	Role       string
	CreatedAt  int64
	ExpiresAt  int64
	CreatedBy  sql.NullString
	ConsumedAt sql.NullInt64
	RevokedAt  sql.NullInt64
}

// Status is invitationStatus, at now.
func (i Invitation) Status(now int64) string {
	switch {
	case i.RevokedAt.Valid:
		return "revoked"
	case i.ConsumedAt.Valid:
		return "consumed"
	case i.ExpiresAt <= now:
		return "expired"
	}
	return "pending"
}

func iso(n sql.NullInt64) any {
	if !n.Valid {
		return nil
	}
	return audit.ISOTime(n.Int64)
}

// JS is serializeInvitation: metadata only, nothing token-derived.
func (i Invitation) JS(now int64) jsvalue.Object {
	name := "Invited user"
	if i.Name.Valid {
		name = i.Name.String
	}
	var by any
	if i.CreatedBy.Valid {
		by = i.CreatedBy.String
	}
	return jsvalue.Object{
		{Key: "id", Value: i.ID}, {Key: "name", Value: name}, {Key: "orgRole", Value: i.Role}, {Key: "status", Value: i.Status(now)},
		{Key: "createdAt", Value: audit.ISOTime(i.CreatedAt)}, {Key: "expiresAt", Value: audit.ISOTime(i.ExpiresAt)},
		{Key: "createdByIdentityId", Value: by}, {Key: "consumedAt", Value: iso(i.ConsumedAt)}, {Key: "revokedAt", Value: iso(i.RevokedAt)},
	}
}

// CreateInvitation is issueInviteGrant: an invitation to the
// Organization as a member or an admin. Inviting an admin is a protected
// operation (admin-step-up's member.invite_admin), with identity.manage
// rechecked once its approval is consumed. A person issues through a live
// membership, read in the job under their gate, so their removal comes
// first (refused here) or after (and revokes this invitation with their
// others). The token is generated by the job that commits and never bound.
func CreateInvitation(ctx context.Context, w *write.Writer, approvals *auth.Service, req Request, organizationID, name, role string, now func() time.Time) (jsvalue.Object, []auth.PendingReport, error) {
	r := req.security(approvals)
	actor := req.Principal.Identity.ID
	person := req.Principal.Identity.Kind == "human"
	var checks []security.Check
	if role == "admin" {
		checks = []security.Check{{Control: security.AdminStepUp, Operation: "member.invite_admin"}}
	}
	member := func(ctx context.Context, db query.DBTX) error {
		if !person {
			return nil
		}
		m, err := readMember(ctx, db, organizationID, actor)
		if err == nil && m == nil {
			err = orgNotFound()
		}
		return err
	}
	var out jsvalue.Object
	var reports []auth.PendingReport
	err := w.Job(ctx, r.Gates(organizationID), func(ctx context.Context, tx *storage.Tx) error {
		p, err := security.Prepare(ctx, tx, r, security.Protected{
			Scope:     write.Scope{OrganizationID: organizationID},
			Checks:    checks,
			Preflight: member,
			Binding: func(ctx context.Context, db query.DBTX, _ *int64) (*auth.Binding, error) {
				if err := member(ctx, db); err != nil {
					return nil, err
				}
				return inviteAdminBinding(organizationID, name), nil
			},
			AuthorizeIn: identityManageIn(req.Principal, organizationID, req.RequestID),
		}, now)
		if err != nil {
			return err
		}
		reports = p.Access
		if person {
			pinned, err := access.PinLiveMembership(ctx, tx, organizationID, actor)
			if err != nil {
				return err
			}
			if !pinned {
				return orgNotFound()
			}
		}
		stored, err := write.Text(name)
		if err != nil {
			return err
		}
		id, token := ids.New(ids.SetupGrant), auth.InviteToken()
		at := now()
		// new Date(Date.now() + INVITE_TTL_MS).toISOString(): milliseconds.
		expires := (at.UnixMilli() + InviteTTL.Milliseconds()) * 1000
		if err := query.New(tx).InsertInvitation(ctx, query.InsertInvitationParams{
			ID: id, TokenHash: auth.HashToken(token), ExpiresAt: expires,
			InviteOrganizationID: sql.NullString{String: organizationID, Valid: true}, InviteRole: sql.NullString{String: role, Valid: true},
			InviteName: sql.NullString{String: stored, Valid: true}, CreatedBy: sql.NullString{String: actor, Valid: true}, CreatedAt: at.UnixMicro(),
		}); err != nil {
			return err
		}
		if err := p.Count(ctx, tx); err != nil {
			return err
		}
		action := "identity.manage"
		md := jsvalue.Object{{Key: "role", Value: role}, {Key: "inviteeName", Value: name}, {Key: "expiresAt", Value: audit.ISOTime(expires)}}
		if _, err := audit.Record(ctx, tx, audit.Event{Type: "invitation.issued", Decision: audit.Info, ActorIdentityID: &actor, OrganizationID: &organizationID,
			Action: &action, Resource: jsvalue.Object{{Key: "invitationId", Value: id}}, Metadata: append(md, security.ApprovalMetadata(p.Approval)...)}); err != nil {
			return err
		}
		out = jsvalue.Object{{Key: "id", Value: id}, {Key: "token", Value: token}, {Key: "expiresAt", Value: audit.ISOTime(expires)}}
		return nil
	})
	if err != nil {
		return nil, nil, err
	}
	return out, reports, nil
}

// RevokeInvitation is revokeInvitation: a pending invitation's token
// stops working at once (consumption takes the same row and refuses a
// revoked grant). Any other status is VERSION_CONFLICT naming it. Recovery
// while frozen; the requester's passkey-verification comes after the
// invitation is found.
func RevokeInvitation(ctx context.Context, w *write.Writer, p *auth.Principal, organizationID, invitationID string, now func() time.Time) ([]auth.PendingReport, error) {
	actor := p.Identity.ID
	var reports []auth.PendingReport
	gates := []write.Gate{write.Organization(organizationID, write.Shared), write.Person(actor, write.Shared)}
	err := w.Job(ctx, gates, func(ctx context.Context, tx *storage.Tx) error {
		if err := write.CheckLive(ctx, tx, write.Scope{OrganizationID: organizationID, DuringFreeze: authz.DuringFreezeRecovery}); err != nil {
			return err
		}
		if err := pgText(invitationID); err != nil {
			return err
		}
		q := query.New(tx)
		row, err := q.InvitationOf(ctx, query.InvitationOfParams{ID: invitationID, InviteOrganizationID: sql.NullString{String: organizationID, Valid: true}})
		if errors.Is(err, sql.ErrNoRows) {
			return domainerr.New("RESOURCE_NOT_FOUND", "Invitation not found")
		}
		if err != nil {
			return err
		}
		// Existence first, then passkey-verification (ADR-0054 Decision 7).
		if reports, err = write.Checkpoint(ctx, tx, p, organizationID); err != nil {
			return err
		}
		at := now().UnixMicro()
		inv := invitationOf(row)
		if status := inv.Status(at); status != "pending" {
			return &domainerr.Error{Code: "VERSION_CONFLICT", Message: "Invitation is no longer pending: it is " + status,
				Details: jsvalue.Object{{Key: "status", Value: status}}}
		}
		if err := q.RevokeInvitationRow(ctx, query.RevokeInvitationRowParams{RevokedAt: sql.NullInt64{Int64: at, Valid: true}, ID: invitationID}); err != nil {
			return err
		}
		action := "identity.manage"
		var invitee any
		if inv.Name.Valid {
			invitee = inv.Name.String
		}
		_, err = audit.Record(ctx, tx, audit.Event{Type: "invitation.revoked", Decision: audit.Info, ActorIdentityID: &actor, OrganizationID: &organizationID,
			Action: &action, Resource: jsvalue.Object{{Key: "invitationId", Value: invitationID}},
			Metadata: jsvalue.Object{{Key: "role", Value: inv.Role}, {Key: "inviteeName", Value: invitee}}})
		return err
	})
	return reports, err
}

func invitationOf(r query.InvitationOfRow) Invitation {
	return Invitation{ID: r.ID, Name: r.InviteName, Role: r.InviteRole.String, CreatedAt: r.CreatedAt, ExpiresAt: r.ExpiresAt,
		CreatedBy: r.CreatedBy, ConsumedAt: r.ConsumedAt, RevokedAt: r.RevokedAt}
}
