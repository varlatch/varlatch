import type { OrgRole } from "../authz/evaluate.js";
import type { Querier } from "../db/migrate.js";
import { labelWithId, quoted } from "./approvallabels.js";
import type { ApprovalBinding, ApprovalChange } from "./approvals.js";

/**
 * admin-step-up for people (ADR-0054 Decision 5, step 4.7): what an
 * approval binds for inviting someone as an admin, promoting a member,
 * demoting an admin and removing a member, per the binding catalogue, and
 * the summary its approver reads. None of these requests carries a secret:
 * an invitation's enrollment token is generated by the server and never
 * bound. Each binds the query `{}` (no route reads one).
 *
 * - member.invite_admin: target the Organization; body `name` and `role`
 *   (always "admin": inviting a member is not on the list); no version.
 * - member.promote / member.demote: target the person (`me` resolved);
 *   body the resulting `role`; the version of their membership the server
 *   reads, checked again under the membership's row lock. The same role
 *   again changes nothing and needs no approval.
 * - member.remove: target the person; no body; the version of their
 *   membership the server reads, checked again under its row lock. A role
 *   change moves that version, so an approval to remove "PERSON (admin)"
 *   is stale once PERSON was demoted. Leaving (the person removing
 *   themselves) is exempt.
 *
 * The last-admin rule refuses before an approval is asked for, and again
 * when it is used (members.ts).
 *
 * Summaries follow approvallabels.ts: every person and the Organization
 * are named by their quoted name and bound id (labelWithId); the
 * invitee, who has no id yet, by their quoted name. Roles are validated
 * enum values and counts are numbers: both are written bare.
 */

const plural = (n: number, word: string) => `${n} ${word}${n === 1 ? "" : "s"}`;

/** A live membership, as a binding and its summary name it. */
export interface MemberRef {
  identityId: string;
  name: string;
  role: OrgRole;
  version: number;
}

/** A person's live membership in the Organization, read without a lock; null when there is none. */
export async function readMember(db: Querier, organizationId: string, identityId: string): Promise<MemberRef | null> {
  const row = (await db.query(
    `SELECT m.identity_id, i.name, m.role, m.version FROM org_memberships m JOIN identities i ON i.id = m.identity_id
     WHERE m.organization_id = $1 AND m.identity_id = $2 AND m.removed_at IS NULL`,
    [organizationId, identityId],
  )).rows[0] as { identity_id: string; name: string; role: OrgRole; version: number } | undefined;
  return row ? { identityId: row.identity_id, name: row.name, role: row.role, version: Number(row.version) } : null;
}

/** member.invite_admin: an invitation for a new admin. */
export function inviteAdminBinding(org: { id: string }, input: { name: string }): ApprovalBinding {
  return {
    operation: "member.invite_admin",
    organizationId: org.id,
    target: { organizationId: org.id },
    body: { name: input.name, role: "admin" },
    query: {},
    expectedVersion: null,
    summary: {
      title: `Invite ${quoted(input.name)} as an Organization Admin`,
      changes: [
        { field: "name", from: null, to: quoted(input.name), loosens: false },
        { field: "role", from: null, to: "admin", loosens: false },
      ],
    },
  };
}

/** member.promote or member.demote of a live membership whose role differs. */
export function memberRoleBinding(org: { id: string }, member: MemberRef, role: OrgRole): ApprovalBinding {
  const change: ApprovalChange = { field: "role", from: member.role, to: role, loosens: false };
  return {
    operation: role === "admin" ? "member.promote" : "member.demote",
    organizationId: org.id,
    target: { identityId: member.identityId },
    body: { role },
    query: {},
    expectedVersion: member.version,
    summary: {
      title: role === "admin"
        ? `Make ${labelWithId(null, member.name, member.identityId)} an Organization Admin`
        : `Make ${labelWithId(null, member.name, member.identityId)} a member instead of an admin`,
      changes: [change],
    },
  };
}

/** What a removal ends, as its summary counts it. */
export interface RemovalCounts {
  grants: number;
  groups: number;
  invitations: number;
}

/**
 * What endMembership (members.ts) would end for this person now, read
 * without a lock: their live direct Grants, their group and team links,
 * and the pending invitations they issued.
 */
export async function removalCounts(db: Querier, organizationId: string, identityId: string): Promise<RemovalCounts> {
  const row = (await db.query(
    `SELECT
       (SELECT count(*)::int FROM grants WHERE organization_id = $1 AND subject_identity_id = $2 AND revoked_at IS NULL) AS grants,
       (SELECT count(*)::int FROM group_members gm JOIN groups g ON g.id = gm.group_id
         WHERE g.organization_id = $1 AND gm.identity_id = $2) AS groups,
       (SELECT count(*)::int FROM setup_grants WHERE kind = 'invite' AND invite_organization_id = $1 AND created_by = $2
         AND consumed_at IS NULL AND revoked_at IS NULL AND expires_at > now()) AS invitations`,
    [organizationId, identityId],
  )).rows[0] as RemovalCounts;
  return { grants: Number(row.grants), groups: Number(row.groups), invitations: Number(row.invitations) };
}

/** member.remove of someone else's live membership. */
export function memberRemoveBinding(org: { id: string; name: string }, member: MemberRef, counts: RemovalCounts): ApprovalBinding {
  return {
    operation: "member.remove",
    organizationId: org.id,
    target: { identityId: member.identityId },
    body: null,
    query: {},
    expectedVersion: member.version,
    summary: {
      title:
        `Remove ${labelWithId(null, member.name, member.identityId)}, ${member.role === "admin" ? "an admin" : "a member"}, ` +
        `from ${labelWithId("organization", org.name, org.id)}: ` +
        `${plural(counts.grants, "direct Grant")} revoked, ${plural(counts.groups, "group")} left, ${plural(counts.invitations, "invitation")} revoked`,
      changes: [],
    },
  };
}
